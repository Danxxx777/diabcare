  idioma() {
    return localStorage.getItem('diabcare_idioma') === 'en' ? 'en' : 'es';
  },

  t(key) {
    const idi = this.idioma();
    return (this.pack[idi] && this.pack[idi][key]) || this.pack.es[key] || key;
  },

  pageMeta(pathname) {
    if (pathname === '/paginas/negocio/farmacia/index.html'
      && new URLSearchParams(window.location.search).get('area') === 'gestion') {
      const idi = this.idioma();
      return idi === 'en'
        ? { title: 'Business and warehouse', sub: 'Procurement, inventory and financial control', crumb: 'Business and warehouse' }
        : { title: 'Negocio y almacén', sub: 'Abastecimiento, inventario y control financiero', crumb: 'Negocio y almacén' };
    }
    const meta = this.pages[pathname];
    if (!meta) return null;
    const idi = this.idioma();
    return {
      title: (meta.title && (meta.title[idi] || meta.title.es)) || '',
      sub: (meta.sub && (meta.sub[idi] || meta.sub.es)) || '',
      crumb: (meta.crumb && (meta.crumb[idi] || meta.crumb.es)) || '',
    };
  },

  aplicarPagina() {
    const meta = this.pageMeta(window.location.pathname);
    if (meta) {
      const crumb = document.querySelector('.topbar .tb-page');
      if (crumb && meta.crumb) crumb.textContent = meta.crumb;
      const title = document.querySelector('.page-title');
      if (title && meta.title) {
        const span = title.querySelector('span');
        if (span) {
          const parts = meta.title.split(/\s+/);
          const last = parts.pop();
          title.innerHTML = `${parts.join(' ')} <span>${last}</span>`;
        } else {
          title.textContent = meta.title;
        }
      }
      const sub = document.querySelector('.page-sub');
      // No pisar subtítulos con reloj/marcadores dinámicos (#ts, etc.)
      if (sub && meta.sub && !sub.id && !sub.querySelector('#ts, [data-i18n-keep]')) {
        sub.textContent = meta.sub;
      }
      if (meta.title) document.title = `DiabCare - ${meta.title}`;
    }
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = this.t(key);
    });

    // Los módulos son formularios y tablas: sin esto, los placeholder,
    // los title y los aria-label se quedan en español al pasar a EN.
    // Uso: data-i18n-attr="placeholder:buscar_paciente; title:ayuda_hba1c"
    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
      const spec = el.getAttribute('data-i18n-attr') || '';
      spec.split(';').forEach((par) => {
        const [attr, key] = par.split(':').map((s) => (s || '').trim());
        if (!attr || !key) return;
        const val = this.t(key);
        if (val === key) return; // clave sin traducir: no pisar el original
        el.setAttribute(attr, val);
      });
    });
  },
